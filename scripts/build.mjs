// Builds the static site into dist/. Zero dependencies.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, DIST, CACHE, getBase, readJson, rmrf, copyDir, validateShowcase, validateSite, inkFor, darkenFor, esc } from './lib.mjs';
import { homePage, gamePage, aboutPage, notFoundPage } from './templates.mjs';

const base = getBase();
const site = readJson(path.join(ROOT, 'site.json'));
const siteErrors = validateSite(site);
if (siteErrors.length) {
  console.error('site.json is invalid:\n' + siteErrors.map((e) => '  - ' + e).join('\n'));
  process.exit(1);
}

function loadBundle(dir) {
  const file = path.join(dir, 'showcase.json');
  if (!fs.existsSync(file)) return { errors: [`${file} not found`] };
  let data;
  try {
    data = readJson(file);
  } catch (err) {
    return { errors: [`showcase.json is not valid JSON: ${err.message}`] };
  }
  const errors = validateShowcase(data, dir);
  return errors.length ? { errors } : { data, dir };
}

// ---- resolve bundles (fetched cache > committed seed)
const games = [];
let failed = false;
for (const { slug } of site.games) {
  const seedDir = path.join(ROOT, 'content', 'games', slug);
  const cacheDir = path.join(CACHE, 'games', slug);
  let source = null;
  let bundle = null;
  if (fs.existsSync(cacheDir)) {
    const r = loadBundle(cacheDir);
    if (r.errors) {
      console.warn(`WARN  ${slug}: fetched bundle is invalid, falling back to seed:\n` + r.errors.map((e) => '        - ' + e).join('\n'));
    } else {
      bundle = r;
      source = 'fetched';
    }
  }
  if (!bundle) {
    const r = loadBundle(seedDir);
    if (r.errors) {
      console.error(`ERROR ${slug}: seed bundle (content/games/${slug}) is invalid:\n` + r.errors.map((e) => '        - ' + e).join('\n'));
      failed = true;
      continue;
    }
    bundle = r;
    source = 'seed';
  }
  const hasDemo = bundle.data.demo.available === true && fs.existsSync(path.join(bundle.dir, 'demo', 'index.html'));
  games.push({ slug, data: bundle.data, dir: bundle.dir, source, hasDemo });
}
if (failed) process.exit(1);

// ---- write output
rmrf(DIST);
fs.mkdirSync(path.join(DIST, 'assets'), { recursive: true });
const write = (rel, content) => {
  const f = path.join(DIST, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, content);
};

fs.copyFileSync(path.join(ROOT, 'src', 'site.css'), path.join(DIST, 'assets', 'site.css'));
fs.copyFileSync(path.join(ROOT, 'src', 'site.js'), path.join(DIST, 'assets', 'site.js'));
fs.copyFileSync(path.join(ROOT, 'src', 'favicon.svg'), path.join(DIST, 'favicon.svg'));

// per-game accent custom properties (no inline styles allowed by the CSP)
const LIGHT_BG = '#f6f3ec';
let accents = '/* generated by scripts/build.mjs */\n';
for (const g of games) {
  const a = g.data.accent.toLowerCase();
  const dark = darkenFor(a, LIGHT_BG);
  const [aw, ah] = g.data.demo.aspect.split('/');
  accents += `[data-game="${g.slug}"]{--accent:${a};--accent-ink:${inkFor(a)};--demo-aspect:${aw}/${ah}}\n`;
  accents += `@media (prefers-color-scheme:light){[data-game="${g.slug}"]{--accent:${dark};--accent-ink:${inkFor(dark)}}}
`;
}
write('assets/accents.css', accents);

write('index.html', homePage({ site, base, games }));
write('about/index.html', aboutPage({ site, base }));
write('404.html', notFoundPage({ site, base }));
for (const g of games) {
  write(`games/${g.slug}/index.html`, gamePage({ site, base, ...g }));
  if (fs.existsSync(path.join(g.dir, 'media'))) copyDir(path.join(g.dir, 'media'), path.join(DIST, 'games', g.slug, 'media'));
  if (g.hasDemo) copyDir(path.join(g.dir, 'demo'), path.join(DIST, 'play', g.slug)); // untouched, no CSP injected
}

const siteUrl = site.url ? site.url.replace(/\/?$/, '/') : '';
write(
  'games.json',
  JSON.stringify(
    {
      site: site.name,
      games: games.map((g) => ({
        slug: g.slug,
        title: g.data.title,
        tagline: g.data.tagline,
        status: g.data.status,
        genre: g.data.genre,
        platforms: g.data.platforms,
        summary: g.data.summary,
        page: `${base}games/${g.slug}/`,
        cover: `${base}games/${g.slug}/${g.data.media.cover}`,
        demo: g.hasDemo ? `${base}play/${g.slug}/` : null,
        updated: g.data.updated || null,
        version: g.data.version || null,
      })),
    },
    null,
    2,
  ) + '\n',
);
write('robots.txt', `User-agent: *\nAllow: /\n${siteUrl ? `Sitemap: ${siteUrl}sitemap.xml\n` : ''}`);
if (siteUrl) {
  const urls = ['', 'about/', ...games.map((g) => `games/${g.slug}/`)];
  write(
    'sitemap.xml',
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((p) => `  <url><loc>${esc(siteUrl + p)}</loc></url>`).join('\n')}\n</urlset>\n`,
  );
}
write('.nojekyll', '');

// ---- summary table
const pad = (s, n) => String(s).padEnd(n);
console.log(`\nBuilt ${games.length} games into dist/ (base ${base})`);
console.log(pad('slug', 18) + pad('source', 9) + pad('demo', 6) + 'title');
for (const g of games) console.log(pad(g.slug, 18) + pad(g.source, 9) + pad(g.hasDemo ? 'yes' : 'no', 6) + g.data.title);
